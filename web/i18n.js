const LANG_ORDER = ['vi', 'en', 'zh'];

function detectLang() {
  try {
    const saved = localStorage.getItem('appLang');
    if (saved && I18N[saved]) return saved;
  } catch (e) { /* storage có thể bị chặn */ }
  const native = window.__APP_LANG__;
  if (native && I18N[native]) return native;
  const nav = (navigator.language || 'vi').toLowerCase();
  if (nav.startsWith('zh')) return 'zh';
  if (nav.startsWith('vi')) return 'vi';
  return 'en';
}

let LANG = detectLang();

function t(key, vars) {
  let s = (I18N[LANG] && I18N[LANG][key]) || I18N.vi[key] || key;
  if (vars) for (const k in vars) s = s.split('{' + k + '}').join(vars[k]);
  return s;
}

// Trường song ngữ trong bộ luật: title_en, advice_zh… — thiếu thì dùng tiếng Việt.
function loc(obj, field) {
  if (!obj) return '';
  return (LANG !== 'vi' && obj[field + '_' + LANG]) || obj[field] || '';
}

function confLabel(c) {
  return t('conf.' + c) || c;
}

function dateLocale() {
  return LANG === 'zh' ? 'zh-CN' : (LANG === 'en' ? 'en-US' : 'vi-VN');
}

function applyStaticI18n() {
  document.documentElement.lang = LANG === 'zh' ? 'zh-Hans' : LANG;
  document.querySelectorAll('[data-i18n]').forEach(el => {
    el.innerHTML = t(el.getAttribute('data-i18n'), { host: 'PanicAnalyzer' });
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    el.placeholder = t(el.getAttribute('data-i18n-placeholder'));
  });
  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    el.title = t(el.getAttribute('data-i18n-title'));
  });
  document.querySelectorAll('.lang-option').forEach(b => {
    b.classList.toggle('active', b.getAttribute('data-lang') === LANG);
  });
  const ver = document.getElementById('settingsVersion');
  if (ver) ver.innerText = window.__APP_VERSION__ || '';
}

function setLang(lang) {
  if (!I18N[lang]) return;
  LANG = lang;
  try { localStorage.setItem('appLang', lang); } catch (e) { /* bỏ qua */ }
  if (window.webkit && window.webkit.messageHandlers && window.webkit.messageHandlers.nativeBridge) {
    window.webkit.messageHandlers.nativeBridge.postMessage({ action: 'setLanguage', lang: lang });
  }
  applyStaticI18n();
  if (typeof onLanguageChanged === 'function') onLanguageChanged();
}

function cycleLang() {
  setLang(LANG_ORDER[(LANG_ORDER.indexOf(LANG) + 1) % LANG_ORDER.length]);
}
